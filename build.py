"""Build a dependency-free MV3 extension from readable sources."""
from pathlib import Path
import json
root=Path(__file__).resolve().parent
core=(root/'src/core.cjs').read_text().split('// Exports are removed by build.py;')[0]
main=(root/'src/ui.js').read_text()
archive=json.dumps((root/'src/archive.py').read_text(),ensure_ascii=True)
extract=json.dumps((root/'src/extract_archive.py').read_text(),ensure_ascii=True)
delete=json.dumps((root/'src/delete_folder.py').read_text(),ensure_ascii=True)
details=json.dumps((root/'src/folder_details.py').read_text(),ensure_ascii=True)
details_ui=(root/'src/details.js').read_text()
progress_ui=(root/'src/progress.js').read_text()
extract_ui=(root/'src/extract.js').read_text()
bundle='// Generated by build.py. Source and tests are included in this package.\n(() => {\n'+core+'\nconst archiveSource = '+archive+';\nconst extractSource = '+extract+';\nconst deleteSource = '+delete+';\nconst detailsSource = '+details+';\n'+progress_ui+'\n'+main+'\n'+details_ui+'\n'+extract_ui+'\n})();\n'
(root/'extension/colab-zip.js').write_text(bundle)
